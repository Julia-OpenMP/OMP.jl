"""
    Frontend

The OpenMP directive front-end: parses `@pragma omp ...` / `@omp ...` into an intermediate
representation ([`Directive`](@ref), [`Clause`](@ref), [`Modifier`](@ref), [`Argument`](@ref)),
validates it against the specification, and hands it to [`lower`](@ref) for code generation.

Organization (hand-written unless noted):

| file                  | content                                                             |
|:----------------------|:--------------------------------------------------------------------|
| `schema.jl`           | `Schema`: types of the specification data                           |
| `generated/`          | `Spec`: the specification data, GENERATED by omp-generator           |
| `conventions.jl`      | how OpenMP is spelled in Julia: aliases, sugar, base language       |
| `registry.jl`         | lookup tables derived from `Spec`                                   |
| `syntax.jl`           | errors and helpers on Julia expressions                             |
| `ir.jl`               | the intermediate representation                                     |
| `parse/`              | parsers, top-down: directive > clause > modifier > argument; `text.jl` splits directive strings |
| `validate.jl`         | syntactic restrictions (unique, required, exclusive, ultimate, ...) |
| `lower.jl`            | code generation entry point                                         |
| `macros.jl`           | `@pragma`, `@omp`, `@pragma_ir`                                     |
"""
module Frontend

export @pragma, @omp, @pragma_ir, OpenMPSyntaxError

include("schema.jl")
using .Schema

include("generated/Spec.jl")

include("syntax.jl")
include("conventions.jl")
include("registry.jl")
include("ir.jl")

include("parse/text.jl")
include("parse/argument.jl")
include("parse/modifier.jl")
include("parse/clause.jl")
include("parse/directive.jl")

include("validate.jl")
include("lower.jl")
include("macros.jl")

end # module Frontend
